/** 소관기관명/부서명 → "시도 시군구" | "시도" | "전국" | null */
export function regionOfOrg(org = "") {
  org = `${org}`;
  let sido = null;
  for (const [canon, re] of SIDO_MATCHERS) if (re.test(org)) { sido = canon; break; }
  if (sido) {
    for (const g of KOREA_SORTED[sido]) if (org.includes(g)) return `${sido} ${g}`;
    return sido; // 시군구 불명 → 시도 단위
  }
  // 시도 토큰이 없을 때: 전국 유일 시군구명으로 보정
  for (const g of Object.keys(UNIQUE_SGG)) if (org.includes(g)) return `${UNIQUE_SGG[g]} ${g}`;
  if (CENTRAL_RE.test(org) || /(부|처|청)$/.test(org.trim())) return NATIONWIDE;
  return null;
}

