// 시군구 매칭은 긴 이름부터(성동구 → 동구 오인 방지)
const KOREA_SORTED = Object.fromEntries(
  SIDO_LIST.map((s) => [s, [...KOREA[s]].sort((a, b) => b.length - a.length)])
);

// 전국에서 유일한 시군구명 → 시도 (시도 토큰이 없을 때 보정용; 중구·동구 등 중복명은 제외)
const UNIQUE_SGG = (() => {
  const cnt = {}, owner = {};
  for (const s of SIDO_LIST) for (const g of KOREA[s]) { cnt[g] = (cnt[g] || 0) + 1; owner[g] = s; }
  const m = {};
  for (const g of Object.keys(cnt)) if (cnt[g] === 1) m[g] = owner[g];
  return m;
})();

